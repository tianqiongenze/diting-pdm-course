def render(t: dict) -> str:
    lines = [
        f"# {t['id']} · {t['title']}",
        "",
        f"> 课程：AI 智能体工程化项目实战 ｜ 讲次：{t['session']} ｜ 学时：4 ｜ 本讲分值：{t['score']} 分",
        "> 组别：__________ ｜ 成员：____________________ ｜ 日期：__________",
        "",
        "## 一、委托背景（企业原话）",
        "",
        f"> {t['background']}",
        "",
        "## 二、任务目标",
        "",
    ]
    for i, o in enumerate(t["objectives"], 1):
        lines.append(f"{i}. {o}")
    lines += ["", "## 三、交付物清单", "", "| 序号 | 文件 | 说明 |", "|---|---|---|"]
    for i, (name, desc) in enumerate(t["deliverables"], 1):
        lines.append(f"| {i} | `{name}` | {desc} |")
    lines += ["", "## 四、约束条件", ""]
    for c in t["constraints"]:
        lines.append(f"- {c}")
    lines += ["", "## 五、实施步骤", ""]
    for i, s in enumerate(t["steps"], 1):
        lines.append(f"{i}. {s}")
    lines += ["", "## 六、验收标准（DoD）", ""]
    for d in t["dod"]:
        lines.append(f"- [ ] {d}")
    lines += ["", "## 七、评分（本讲）", "", "| 评分点 | 权重 |", "|---|---|"]
    for item, w in t["scoring"]:
        lines.append(f"| {item} | {w} |")
    lines += [
        "",
        "## 八、提交要求",
        "",
        f"- 位置：小组仓库 `artifacts/{t['id']}_{t['title']}/`",
        f"- 命名：`{t['id']}_{t['title']}_第N组_v1`",
        "- 截止：本讲课后 48 小时内（逾期 ×0.8，超过 1 周不计分）",
        "- 必写：同目录 `README.md`（做了什么、怎么验证、遗留问题）",
        "",
        "## 九、思考题",
        "",
    ]
    for q in t["questions"]:
        lines.append(f"1. {q}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for t in TASKS:
        path = OUT / f"{t['id']}_{t['title']}.md"
        path.write_text(render(t), encoding="utf-8")
        print("written:", path.name)
    print(f"total {len(TASKS)} task books")


if __name__ == "__main__":
    main()
